/* מספר אקראי קבוע לפי מחרוזת (אותו תאריך → אותו רצף) */
function rng(seedStr) {
  let h = 2166136261;
  for (const c of seedStr) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); }
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TZ = "Asia/Jerusalem";
function localDay(d) {
  return new Intl.DateTimeFormat("en-CA", { timeZone: TZ, year: "numeric", month: "2-digit", day: "2-digit" }).format(d);
}
/* חצות מקומית של היום (UTC) */
function localMidnight(day) {
  const guess = new Date(day + "T00:00:00Z");
  const hh = Number(new Intl.DateTimeFormat("en-GB", { timeZone: TZ, hour: "2-digit", hourCycle: "h23" }).format(guess));
  return new Date(guess.getTime() - hh * 3600000);
}

/* התוכנית של יום אחד: רשימת אירועים {key, at, kind:"thread"|"post", ...} */
function dayPlan(day) {
  const r = rng("progbot-demo-" + day);
  const base = localMidnight(day).getTime();
  const n = 18 + Math.floor(r() * 9); /* 18–26 הודעות ביום */
  const order = BANK.map((b, i) => [r(), i]).sort((a, b) => a[0] - b[0]).map((x) => x[1]);
  const out = [];
  let k = 0;
  for (let i = 0; i < n; i++) {
    const minute = 8 * 60 + Math.floor(r() * 15 * 60); /* 08:00–23:00 */
    const at = new Date(base + minute * 60000 + Math.floor(r() * 59) * 1000);
    const author = AUTHORS[Math.floor(r() * AUTHORS.length)];
    if (i > 2 && r() < 0.25) {
      out.push({ key: `${day}-${k++}`, at, kind: "post", author, text: FOLLOWUPS[Math.floor(r() * FOLLOWUPS.length)], pick: r() });
    } else {
      const [forum, title, text] = BANK[order[i % order.length]];
      out.push({ key: `${day}-${k++}`, at, kind: "thread", forum, title, author, text });
    }
  }
  return out.sort((a, b) => a.at - b.at);
}

/*
  מוסיף לפורום את כל ההודעות של היום (ושל אתמול) שהגיע זמנן ועוד לא נוספו.
  adapter: MemoryAdapter. now: Date.
*/
function materialize(adapter, now = new Date()) {
  const added = [];
  const today = localDay(now);
  const yesterday = localDay(new Date(now.getTime() - 24 * 3600000));
  for (const day of [yesterday, today]) {
    const dayThreads = [];
    for (const ev of dayPlan(day)) {
      if (ev.at > now) break;
      const tid = "live-" + ev.key;
      if (ev.kind === "thread") {
        if (!adapter.threads.has(tid)) {
          adapter.seedThread({ id: tid, forum: ev.forum, title: ev.title, author: ev.author, text: ev.text, at: ev.at.toISOString(), postId: "lp-" + ev.key });
          added.push(tid);
        }
        dayThreads.push(tid);
      } else if (dayThreads.length) {
        const target = dayThreads[Math.floor(ev.pick * dayThreads.length)];
        const t = adapter.threads.get(target);
        const pid = "lp-" + ev.key;
        if (t && !t.posts.some((p) => p.id === pid)) {
          adapter.addPost({ threadId: target, author: ev.author, text: ev.text, at: ev.at.toISOString(), id: pid });
          added.push(pid);
        }
      }
    }
  }
  return added;
}

module.exports = { materialize, dayPlan, localDay, BANK };
